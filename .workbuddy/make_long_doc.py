"""造一份长文档（>2000 字）+ 内嵌图片，验证分段抽取路径下图片内容不丢"""
from pathlib import Path

import docx
from docx.shared import Inches

base = Path(__file__).parent
kb = base.parent / "kb_test"
p1 = base / "fig_table.png"
p2 = base / "fig_chart.png"

doc = docx.Document()
doc.add_heading("2026年第三季度经营分析报告", level=1)
doc.add_paragraph(
    "本报告面向管理层，汇总第三季度的经营结果、成本结构、渠道表现与人员情况，"
    "并对四季度的工作重点提出建议。数据口径与财务系统一致，未经审计。"
)

doc.add_heading("一、经营概况", level=2)
doc.add_paragraph(
    "第三季度公司实现营业收入1.28亿元，同比增长23.5%，环比增长8.2%，"
    "增长主要来自华东区新签客户和存量客户的复购。营业成本0.79亿元，"
    "毛利率38.2%，同比下降2.1个百分点，环比下降0.8个百分点。"
    "毛利率下滑的直接原因是主要原材料采购单价上涨约15%，"
    "而产品售价受竞争影响仅上调3%，成本传导存在明显滞后。"
)
doc.add_paragraph(
    "费用方面，销售费用2100万元，同比增长18.6%；管理费用960万元，同比增长6.4%；"
    "研发费用1580万元，占营业收入的12.3%，同比提升1.8个百分点，"
    "主要投入在新型号的电控系统和结构件轻量化两个方向。"
    "三项费用合计占营业收入的36.2%，较去年同期上升1.1个百分点。"
)
doc.add_paragraph("核心经营指标见下图：")
doc.add_picture(str(p1), width=Inches(6))

doc.add_heading("二、渠道与区域表现", level=2)
doc.add_paragraph(
    "从渠道看，直销收入6800万元，占比53.1%，同比增长31.2%，是增长的主要来源；"
    "经销收入4600万元，占比35.9%，同比增长12.8%；线上收入1400万元，"
    "占比10.9%，同比增长45.6%，基数小但增速最快。"
)
doc.add_paragraph(
    "从区域看，华东区收入5200万元，占比40.6%，同比增长36.4%；"
    "华南区3100万元，占比24.2%，同比增长19.1%；华北区2800万元，占比21.9%，"
    "同比增长9.3%；其他区域1700万元，占比13.3%，同比下降4.2%。"
    "华北区增长放缓主要受两家大客户招标延期影响，预计四季度回补。"
)
doc.add_paragraph(
    "客户结构方面，前五大客户合计收入4800万元，占比37.5%，集中度较去年下降3.2个百分点，"
    "说明客户结构趋于分散，单一客户流失的冲击在减小。"
    "新增客户127家，其中年采购额超过100万元的有9家。"
)

doc.add_heading("三、人员与组织", level=2)
doc.add_paragraph(
    "截至季末，公司员工总数480人，较年初增加52人。其中研发人员142人，占比29.6%；"
    "生产人员186人，占比38.8%；销售与市场人员98人，占比20.4%；"
    "管理及职能人员54人，占比11.2%。"
)
doc.add_paragraph(
    "人员流动方面，季度主动离职率4.1%，低于去年同期的5.3%。"
    "研发条线的离职率2.8%，核心岗位保持稳定。"
    "人均创收26.7万元，同比提升14.2%；人均创利4.3万元，同比下降3.1%，"
    "与毛利率下滑相互印证。"
)
doc.add_paragraph("季度收入走势见下图：")
doc.add_picture(str(p2), width=Inches(5.5))

doc.add_heading("四、风险与四季度措施", level=2)
doc.add_paragraph(
    "第一，原材料价格风险。主要原材料价格已连续三个季度上涨，"
    "若四季度继续上行，全年毛利率可能跌破37%。措施：与两家核心供应商签订半年期长协价，"
    "锁定60%的用量；同时启动替代料验证，预计十一月完成小批量试产。"
)
doc.add_paragraph(
    "第二，应收账款风险。季末应收账款余额8600万元，较年初增加2100万元，"
    "周转天数从62天延长到71天。措施：对超过90天的账款启动专项催收，"
    "并对新签合同提高预付款比例至30%。"
)
doc.add_paragraph(
    "第三，产能风险。现有产线在四季度的订单排产已接近满负荷，"
    "若华北区招标回补，可能出现交付延迟。措施：与两家外协厂签订弹性产能协议，"
    "预留15%的产能余量。"
)
doc.add_paragraph(
    "四季度重点：一是完成新型号量产导入，二是把毛利率拉回38%以上，"
    "三是新签客户数量再增40家，四是应收账款周转天数压回65天以内。"
)

out = kb / "长文档_带图片_季度报告.docx"
doc.save(out)
chars = sum(len(p.text) for p in doc.paragraphs)
print("已生成:", out)
print("正文字数:", chars, "总字节:", out.stat().st_size)
